    public function register_hooks()
    {
        add_filter('gettext_zebracode-blog-ai', array($this, 'translate'), 10, 3);
        add_filter('ngettext_zebracode-blog-ai', array($this, 'translate_plural'), 10, 5);
    }

    public function translate($translation, $text, $domain)
    {
        if (!$this->is_persian() || $domain !== 'zebracode-blog-ai') {
            return $translation;
        }

        return isset(self::$translations[$text]) ? self::$translations[$text] : $translation;
    }

    public function translate_plural($translation, $single, $plural, $number, $domain)
    {
        if (!$this->is_persian() || $domain !== 'zebracode-blog-ai') {
            return $translation;
        }

        $key = $number === 1 ? $single : $plural;
        return isset(self::$translations[$key]) ? sprintf(self::$translations[$key], $number) : $translation;
    }

    private function is_persian()
    {
        $locale = function_exists('get_locale') ? (string) get_locale() : '';
        return strpos($locale, 'fa') === 0 || (function_exists('is_rtl') && is_rtl());
    }
